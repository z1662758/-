export function enrichAgentBehaviors(profile){
  if(profile.behavior_schema_revision>=2)return profile
  const rules=[...(profile.behavior_rules||[])],ids=new Set(rules.map(x=>x.id))
  for(const [id,trigger,method,definition] of specifications[profile.actor_type]||[])if(!ids.has(id)){rules.push({id,trigger,method,definition});ids.add(id)}
  return {...profile,behavior_schema_revision:2,behavior_rules:rules}
}
