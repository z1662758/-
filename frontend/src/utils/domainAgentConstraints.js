export function enrichAgentConstraints(profile,model){
  if(profile.constraint_schema_revision>=2)return profile
  const additions=[...common,...(roles[profile.actor_type]||[]),...(model.world_model?.scenario==='uranium'||model.industry==='uranium'?uranium:[])].map(row=>row.join('｜'))
  return {...profile,constraint_schema_revision:2,constraints:[...new Set([...(profile.constraints||[]),...additions])]}
}
export function constraintSections(profile){
  const groups=new Map()
  for(const [index,text] of (profile?.constraints||[]).entries()){
    const parts=text.split('｜'),structured=parts.length>=4
    const item=structured?{category:parts[0],label:parts[1],condition:parts[2],response:parts.slice(3).join('｜')}:{category:'基础边界',label:`基础约束 ${index+1}`,condition:text,response:'按已定义的业务处理流程记录并反馈'}
    if(!groups.has(item.category))groups.set(item.category,[])
    groups.get(item.category).push(item)
  }
  return [...groups].map(([category,items])=>({category,items})).sort((a,b)=>Number(a.category==='基础边界')-Number(b.category==='基础边界'))
}
