export function applyUraniumDecisionCopy(branch, scenarioKey, timeIndex, baseline = false) {
  if (!branch) return branch
  branch = structuredClone(branch)
  branch.action = baseline ? '维持原采购与调运安排（未干预基线）' : '执行供应链协同调控寻优（调控路径）'
  branch.desc = baseline ? '不实施主动干预，观察地缘与通道扰动沿供应链网络自然演化的后果。' : '依托扩展式博弈决策树，对比多式联运绕行、战略储备平准与现货采购等应对对策。'
  branch.reasoning = uraniumDecisionReasoning(branch.action, branch.desc)

  const key = strategies[scenarioKey] ? scenarioKey : 'rawShortage'
  const tIdx = Math.max(0, Math.min(2, Number(timeIndex) || 0))

  branch.children.forEach((node, index) => {
    if (baseline) {
      const statePair = baselineStates[key]?.[tIdx] || baselineStates.rawShortage[1]
      node.action = statePair[index % statePair.length]
      node.desc = `${node.action}，单一来源依赖导致系统脆弱性持续恶化。`
      if (node.outcome) node.outcome.situation = node.desc
    } else {
      const stList = strategies[key]?.[tIdx] || strategies.rawShortage[1]
      const [action, desc, success, constraint] = stList[index % stList.length]
      node.action = action
      node.desc = desc
      node.children?.forEach((leaf, leafIndex) => {
        leaf.action = leafIndex === 0 ? success : constraint
        leaf.name = leaf.action
        leaf.desc = `${leaf.action}，最终履约完成率达 ${leaf.outcome?.fulfillmentRate || '98%'}。`
        if (leaf.outcome) leaf.outcome.situation = leaf.desc
      })
    }
    node.name = node.action
    node.reasoning = uraniumDecisionReasoning(node.action, node.desc)
  })
  return branch
}
