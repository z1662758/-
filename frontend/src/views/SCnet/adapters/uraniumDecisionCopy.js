export function uraniumDecisionReasoning(action, description) {
  return {
    thinkingSteps: [description, `核对“${action}”所需的供给、库存和运输条件。`, '比较分支结果的交付完成率与综合评分，跟踪执行偏差。'],
    sources: [
      { type: '实验输入', name: '当前实验的年度事件与供需状态', snippet: '结合所选实验的风险、库存覆盖和供需缺口识别处置重点。' },
      { type: '评估依据', name: '候选动作与分支结果', snippet: '按分支概率计算预期综合评分，并与未干预基线比较。' },
    ],
  }
}

export function applyUraniumDecisionCopy(branch, scenarioKey, timeIndex, baseline = false) {
  if (!branch) return branch
  branch = structuredClone(branch)
  branch.action = baseline ? '维持原采购与调运安排' : '执行供应链协同调控'
  branch.desc = baseline ? '沿用现有方案，观察供给、库存和交付状态的变化。' : '比较采购调整、库存调拨与运输协调等候选动作。'
  branch.reasoning = uraniumDecisionReasoning(branch.action, branch.desc)
  branch.children.forEach((node, index) => {
    if (baseline) {
      node.action = baselineStates[scenarioKey][timeIndex][index]
      node.desc = `${node.action}，需要继续跟踪供给、库存与交付变化。`
      node.outcome.situation = node.desc
    } else {
      const [action, desc, success, constraint] = strategies[scenarioKey][timeIndex][index]
      node.action = action
      node.desc = desc
      node.children.forEach((leaf, leafIndex) => {
        leaf.action = leafIndex === 0 ? success : constraint
        leaf.name = leaf.action
        leaf.desc = `${leaf.action}，交付完成率预计为 ${leaf.outcome.fulfillmentRate}。`
        leaf.outcome.situation = leaf.desc
      })
    }
    node.name = node.action
    node.reasoning = uraniumDecisionReasoning(node.action, node.desc)
  })
  return branch
}
